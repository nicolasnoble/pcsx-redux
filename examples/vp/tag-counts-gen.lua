-- Writes tag-counts.lua: how often each control-code tag occurs in the room
-- scripts of a disc, each distinct script counted once (rooms share scripts).
--
--   VP_DISC1=<disc.cue> pcsx-redux -cli -dofile examples/vp/tag-counts-gen.lua
--
-- VP_TAGCOUNTS_OUT overrides the output path (default: next to this script).
local here = debug.getinfo(1, 'S').source:match('^@(.*/)') or './'
Support.extra.dofile(here .. 'browser.lua')
local iso = PCSX.openIso(os.getenv('VP_DISC1'))
local disc = VP.vfs.identify(iso)
if not disc then print('FAIL: not a Valkyrie Profile disc') return PCSX.quit(1) end

local tags, done = {}, {}
local stats = { rooms = 0, scripts = 0, strings = 0 }
local function walk(node)
    local children = VP.vfs.expand(node)
    for _, v in ipairs(node.viewers) do
        if v.load and v.name == 'Room script' then
            local ptrs = VP.vfs.ptrs(v)
            local extra = v.extra
            if ptrs and extra.key and extra.style == 'primary' then
                stats.rooms = stats.rooms + 1
                if not done[extra.key] then
                    done[extra.key] = true
                    stats.scripts = stats.scripts + 1
                    local i = extra.first
                    while extra.tokens[i] do
                        stats.strings = stats.strings + 1
                        local inString = {}
                        for _, t in ipairs(extra.tokens[i]) do
                            if t.c then
                                local name = VP.text.tagName(t, 'primary') or 'newline'
                                local e = tags[name] or { n = 0, strings = 0 }
                                tags[name] = e
                                e.n = e.n + 1
                                if not inString[name] then inString[name] = true e.strings = e.strings + 1 end
                            end
                        end
                        i = i + 1
                    end
                end
            end
        end
    end
    for _, c in ipairs(children) do walk(c) end
end
local function walkDir(dir)
    for _, c in ipairs(VP.vfs.expand(dir)) do
        if c.isDir then walkDir(c) else walk(c) end
    end
end
walkDir(VP.vfs.expand(VP.vfs.root(iso))[2])

local names = {}
for k in pairs(tags) do names[#names + 1] = k end
table.sort(names)
local out = { '-- Generated by tag-counts-gen.lua; do not edit.',
    string.format('VP.tags = VP.tags or {}\nVP.tags.counts = { disc = %q, rooms = %d, scripts = %d, strings = %d, tags = {',
        string.format('%s %s disc %d', disc.exe, disc.region, disc.disc), stats.rooms, stats.scripts, stats.strings) }
for _, k in ipairs(names) do
    out[#out + 1] = string.format('    [%q] = { n = %d, strings = %d },', k, tags[k].n, tags[k].strings)
end
out[#out + 1] = '} }'
local path = os.getenv('VP_TAGCOUNTS_OUT') or (here .. 'tag-counts.lua')
local f = assert(io.open(path, 'w'))
f:write(table.concat(out, '\n') .. '\n')
f:close()
print(string.format('wrote %s: %d rooms, %d distinct scripts, %d strings, %d tags', path, stats.rooms, stats.scripts,
    stats.strings, #names))
PCSX.quit(0)
